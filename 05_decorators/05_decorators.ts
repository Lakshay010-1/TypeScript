// Decorators
// They are special functions that can be attached to a class or class member to observe, modify, replace, or add behavior/metadata to the decorated element.
// Starts with @

// Decorator Factory
// They are used to create decorators that accept arguments.

// Decorator Models
// 1. Standard ECMAScript Decorators
// - Doesn't support paramter decorator
// - API = (value, context)
// - JavaScript/ECMAScript Standard

// 2. Legacy/Experimental Decorators
// - Doesn't support Accessor decorator
// - API = (target, propertyKey, descriptor)
// - TypeScript Specific
// - use TypeScript-specific semantics
// - Needs to be enabled in tsconfig.json file inside compilerOptions
